export function getPlaceContent(placeOrId, language = 'en') {
  const id = typeof placeOrId === 'string' ? placeOrId : placeOrId?.id;
  return placeContent[id]?.[language] || null;
}

export function localizePlace(place, language = 'en') {
  if (!place || language === 'en') return place;
  const content = getPlaceContent(place, language);
  if (!content) return place;
  return {
    ...place,
    localizedName: content.name,
    englishName: place.title,
    shortDescription: content.shortDescription,
    overview: content.overview,
    keyHighlights: content.highlights,
    tags: content.tags,
    visitorGuidelines: { ...place.visitorGuidelines, ...content.visitorGuidelines },
    nearbyDining: (place.nearbyDining || []).map((entry, index) => ({
      ...entry,
      ...(content.nearbyDining[index] || {}),
    })),
  };
}

export default placeContent;
